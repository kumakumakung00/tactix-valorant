export function getCompsForMapAndPlay(
  mapId: string,
  side: Side,
  play?: StrategyPlay
): (MapCompRecommendation & { matchScore: number; isBestForPlay: boolean })[] {
  const mapComps = MAP_COMP_RECOMMENDATIONS.filter((c) => c.mapId === mapId);
  const playText = `${play?.name ?? ''} ${play?.roundType ?? ''} ${
    play?.steps.map((s) => s.text).join(' ') ?? ''
  }`.toLowerCase();

  const scored = mapComps.map((comp) => {
    let score = 0;
    if (comp.sideFocus === side) score += 3;
    else if (comp.sideFocus === 'both') score += 2;

    for (const kw of comp.fitKeywords) {
      if (playText.includes(kw.toLowerCase())) {
        score += 4;
      }
    }
    return { ...comp, matchScore: score };
  });

  scored.sort((a, b) => b.matchScore - a.matchScore);
  const topScore = scored[0]?.matchScore ?? 0;

  return scored.map((c, idx) => ({
    ...c,
    isBestForPlay: idx === 0 && topScore > 0,
  }));
}

export function getMetaAgentSetForMap(mapId: string): Set<string> {
  const set = new Set<string>();
  for (const c of MAP_COMP_RECOMMENDATIONS) {
    if (c.mapId === mapId) {
      c.agents.forEach((a) => set.add(a));
    }
  }
  return set;
}
